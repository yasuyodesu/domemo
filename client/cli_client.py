import os
import sys

# プロジェクトルートのパスを通す
sys.path.append(os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

from core.game_state import ドメモ進行管理

def 画面をクリア():
    """画面を綺麗にする（Windows/Mac両対応）"""
    os.system('cls' if os.name == 'nt' else 'clear')

def ドメモプレイ():
    print("==========================================")
    print("           DOMEMO（ドメモ） CUI版          ")
    print("==========================================")
    
    # 参加人数の設定
    while True:
        try:
            人数 = int(input("参加人数を入力してください (2〜5人): "))
            if 2 <= 人数 <= 5:
                break
            print("2〜5人で入力してください。")
        except ValueError:
            print("半角数字で入力してください。")

    # ゲーム初期化
    ゲーム = ドメモ進行管理(参加人数=人数)
    
    # ゲームループ
    while not ゲーム.ゲーム終了フラグ:
        手番プレイヤー = ゲーム.現在のプレイヤーID
        
        画面をクリア()
        print(f"==========================================")
        print(f"       ★ プレイヤー {手番プレイヤー} の手番です ★")
        print(f"==========================================")
        
        # 現在の手番プレイヤー視点の表示データを取得
        表示データ = ゲーム.プレイヤー用の表示データを取得(手番プレイヤー)
        
        # 画面表示
        print(f"\n【公開カード（場札）】: {表示データ['公開カード']}")
        print(f"【これまでの捨て札】  : {表示データ['場の捨て札']}\n")
        
        print("【全員の手札状況】")
        for プレイヤーID, 手札 in 表示データ["全員の手札"].items():
            if プレイヤーID == 手番プレイヤー:
                print(f"  ▶ プレイヤー {プレイヤーID} (あなた) : {手札}")
            else:
                print(f"     プレイヤー {プレイヤーID}          : {手札}")
        
        print("\n------------------------------------------")
        if 表示データ["直近の履歴"]:
            直近 = 表示データ["直近の履歴"][-1]
            結果表示 = "【当たり！】" if 直近["当たり"] else "【ハズレ】"
            print(f"前回の宣言: プレイヤー {直近['プレイヤーID']} が「{直近['宣言した数字']}」を宣言 ➔ {結果表示}")
        print("------------------------------------------")

        # 数字の入力
        while True:
            try:
                宣言 = int(input(f"\nプレイヤー {手番プレイヤー} さん、自分の手札にあると思う数字 (1〜7) を宣言してください: "))
                if 1 <= 宣言 <= 7:
                    # 判定実行
                    結果 = ゲーム.数字を宣言する(手番プレイヤー, 宣言した数字=宣言)
                    break
                print("1〜7の数字を入力してください。")
            except ValueError:
                print("半角数字で入力してください。")

        # 結果の簡易表示
        if 結果["当たり"]:
            print(f"\n✨ 正解！ 自分の手札に 「{宣言}」 がありました！")
            if 結果["ゲーム終了"]:
                break
            print("正解したので連続手番です！（Enterを押して次へ）")
        else:
            print(f"\n❌ 残念... 自分の手札に 「{宣言}」 はありませんでした。")
            print("次のプレイヤーに交代します。（Enterを押して次へ）")
            
        input()

    # 勝者発表
    画面をクリア()
    print("==========================================")
    print("             🎉 GAME OVER 🎉              ")
    print("==========================================")
    勝者 = ゲーム.勝者ID
    print(f"\nプレイヤー {勝者} がすべての手札をオープンしました！")
    print(f"🏆 勝利者: プレイヤー {勝者} 🏆\n")
    print("全員の最終手札:")
    for プレイヤーID, 手札 in ゲーム.全員の手札.items():
        print(f"  プレイヤー {プレイヤーID}: {手札}")

if __name__ == "__main__":
    ドメモプレイ()